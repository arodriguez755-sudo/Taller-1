#include <iostream>

using namespace std;

int main() {
    int x, y;

    // Lectura de los dos números enteros
    cout << "Ingrese el primer numero entero (x): ";
    cin >> x;

    cout << "Ingrese el segundo numero entero (y): ";
    cin >> y;

    // Muestra de los valores ingresados
    cout << "\nLos valores ingresados son:" << endl;
    cout << "x = " << x << endl;
    cout << "y = " << y << endl;

    return 0;
}
